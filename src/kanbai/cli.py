"""Kanbai CLI — the main entry point.

Commands:
    kanbai init [--no-git]      Scaffold .kanbai/ in the current directory.
    kanbai serve                Launch UI + MCP server (SSE) for humans.
    kanbai serve --mcp          Launch headless MCP server (stdio) for agents.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import importlib.metadata

import typer

app = typer.Typer(
    name="kanbai",
    help="AI-powered Kanban board — per-repo sidecar for humans and agents.",
    no_args_is_help=False,
    add_completion=False,
    invoke_without_command=True,
)


def _version_callback(value: bool) -> None:
    if value:
        version = importlib.metadata.version("kanbai")
        typer.echo(f"kanbai {version}")
        raise typer.Exit()


@app.callback(invoke_without_command=True)
def _default(
    ctx: typer.Context,
    version: bool = typer.Option(
        None, "--version", "-v",
        callback=_version_callback,
        is_eager=True,
        help="Show version and exit.",
    ),
) -> None:
    """When no subcommand is given, launch the board (equivalent to `kanbai serve`)."""
    if ctx.invoked_subcommand is None:
        # Check if .kanbai/ exists; if not, show help
        root = find_kanbai_root()
        if root is None:
            typer.echo(
                "No .kanbai/ found. Run 'kanbai init' first, or 'kanbai --help' for commands.",
                err=True,
            )
            raise typer.Exit(1)
        _set_project_env(root)
        from dotenv import load_dotenv
        env_file = root / ".env"
        if env_file.exists():
            load_dotenv(env_file)
        typer.echo(f"[kanbai] project: {root}")
        typer.echo(f"[kanbai] UI: http://localhost:8765")
        typer.echo(f"[kanbai] MCP (SSE): http://localhost:3001/sse")
        _run_ui_and_mcp(root, 8765, 3001)


# ─── Helpers ────────────────────────────────────────────────────────────────────

KANBAI_DIR_NAME = ".kanbai"


def find_kanbai_root(start: Path | None = None) -> Path | None:
    """Walk up from *start* (default cwd) looking for a .kanbai/ directory."""
    current = (start or Path.cwd()).resolve()
    while True:
        candidate = current / KANBAI_DIR_NAME
        if candidate.is_dir():
            return current
        parent = current.parent
        if parent == current:
            return None
        current = parent


def require_kanbai_root() -> Path:
    """Return the project root or exit with an error message."""
    root = find_kanbai_root()
    if root is None:
        typer.echo(
            "Error: No .kanbai/ directory found in this directory or any parent.\n"
            "Run 'kanbai init' to set up a board for this project.",
            err=True,
        )
        raise typer.Exit(1)
    return root


def _set_project_env(project_root: Path) -> None:
    """Point kanbai's paths module at the given project root."""
    os.environ["KANBAI_PROJECT_PATH"] = str(project_root)


# ─── Commands ───────────────────────────────────────────────────────────────────


@app.command()
def init(
    no_git: bool = typer.Option(False, "--no-git", help="Disable git tracking for this board."),
    from_path: str = typer.Option(None, "--from", help="Import existing board_data/ directory (migration)."),
) -> None:
    """Initialize a .kanbai/ board in the current directory."""
    cwd = Path.cwd()
    kanbai_dir = cwd / KANBAI_DIR_NAME

    if kanbai_dir.exists():
        typer.echo(f".kanbai/ already exists in {cwd}")
        raise typer.Exit(0)

    if from_path:
        # Migration: copy from existing board_data/
        import shutil
        src = Path(from_path).resolve()
        if not src.is_dir():
            typer.echo(f"Error: {src} is not a directory.", err=True)
            raise typer.Exit(1)
        shutil.copytree(src, kanbai_dir)
        # Ensure settings has git_tracking and project_root keys
        settings_file = kanbai_dir / "settings.json"
        if settings_file.exists():
            import json as _json
            data = _json.loads(settings_file.read_text())
            if "git_tracking" not in data:
                data["git_tracking"] = not no_git
            if "project_root" not in data:
                data["project_root"] = str(cwd.resolve())
            settings_file.write_text(_json.dumps(data, indent=2))
        # Ensure .gitignore
        gitignore = kanbai_dir / ".gitignore"
        if not gitignore.exists():
            gitignore.write_text(
                "# Auto-generated by kanbai — do not edit manually.\n"
                ".cache.db\n"
                "ui_state.json\n"
            )
        typer.echo(f"✓ Migrated board from {src} → {kanbai_dir}")
        return

    # Create directory structure
    kanbai_dir.mkdir()
    for lane in ("backlog", "in_progress", "review", "done", "attachments"):
        (kanbai_dir / lane).mkdir()

    # counter.json
    (kanbai_dir / "counter.json").write_text(json.dumps({"next": 1}, indent=2))

    # epics.json
    (kanbai_dir / "epics.json").write_text(json.dumps({}, indent=2))

    # settings.json
    settings = {
        "git_tracking": not no_git,
        "project_root": str(cwd.resolve()),
        "use_local_tz": True,
        "reasoning_effort": "none",
        "max_completion_tokens": 2048,
        "stream_response": True,
        "max_agent_steps": 8,
    }
    (kanbai_dir / "settings.json").write_text(json.dumps(settings, indent=2))

    # .gitignore for derived files
    (kanbai_dir / ".gitignore").write_text(
        "# Auto-generated by kanbai — do not edit manually.\n"
        ".cache.db\n"
        "ui_state.json\n"
    )

    # transitions log
    (kanbai_dir / "transitions.jsonl").write_text("")

    # activity log
    (kanbai_dir / "activity.jsonl").write_text("")

    # models.yml — AI model config (chat panel)
    (kanbai_dir / "models.yml").write_text(
        "# AI models for the kanbai chat panel.\n"
        "# Each entry maps a display handle to an env var holding the model/deployment name.\n"
        "# The chat panel won't work until at least one valid model is configured.\n"
        "models:\n"
        "  - handle: default\n"
        "    env_var: OPENAI_MODEL\n"
    )

    # README.md — copy from kanbai package so users always have docs
    import shutil
    from kanbai.paths import INSTALL_ROOT
    # Try package-bundled copy first, then fall back to repo root (dev)
    pkg_readme = INSTALL_ROOT / "docs" / "README.md"
    repo_readme = INSTALL_ROOT.parent.parent / "README.md"
    for candidate in (pkg_readme, repo_readme):
        if candidate.exists():
            shutil.copy2(candidate, kanbai_dir / "README.md")
            break

    typer.echo(f"✓ Initialized kanbai board in {kanbai_dir}")
    if no_git:
        typer.echo("  Git tracking: disabled")
    else:
        typer.echo("  Git tracking: enabled")
    typer.echo("\n  Next steps:")
    typer.echo("    kanbai serve        — open board UI + MCP server")
    typer.echo("    kanbai serve --mcp  — headless MCP for AI agents")


@app.command()
def serve(
    mcp: bool = typer.Option(False, "--mcp", help="Run headless MCP server over stdio (for AI agent clients)."),
    port: int = typer.Option(8765, "--port", help="Port for the UI web server."),
    mcp_port: int = typer.Option(3001, "--mcp-port", help="Port for the MCP SSE server (when running with UI)."),
) -> None:
    """Start the kanbai server.

    Without --mcp: launches the Flet UI (human command center) and an MCP
    server on SSE transport so agents can connect.

    With --mcp: launches a headless MCP server over stdio for agent clients
    (no UI, no browser).
    """
    project_root = require_kanbai_root()
    _set_project_env(project_root)

    from kanbai.board import settings as _settings
    _settings.set_project_root(str(project_root))

    # Load .env from project root if present
    from dotenv import load_dotenv
    env_file = project_root / ".env"
    if env_file.exists():
        load_dotenv(env_file)

    if mcp:
        # Headless stdio MCP for agent clients
        typer.echo(f"[kanbai] MCP server (stdio) — project: {project_root}", err=True)
        typer.echo(f"[kanbai] Add this to your agent's MCP config:", err=True)
        typer.echo(f'  {{"command": "kanbai", "args": ["serve", "--mcp"]}}', err=True)
        from kanbai.mcp_server.server import run_mcp_server
        run_mcp_server()
    else:
        # UI + MCP SSE
        typer.echo(f"[kanbai] project: {project_root}")
        typer.echo(f"[kanbai] UI: http://localhost:{port}")
        typer.echo(f"[kanbai] MCP (SSE): http://localhost:{mcp_port}/sse")
        _run_ui_and_mcp(project_root, port, mcp_port)


def _run_ui_and_mcp(project_root: Path, ui_port: int, mcp_port: int) -> None:
    """Launch the Flet UI and MCP SSE server together."""
    import threading

    # Start MCP SSE in a background thread (delayed to avoid fighting Flet for CPU)
    def _mcp_sse():
        from kanbai.mcp_server.server import mcp
        mcp.run(transport="sse", port=mcp_port)

    mcp_thread = threading.Thread(target=_mcp_sse, daemon=True)
    mcp_thread.start()

    # Run the Flet UI (blocks)
    from kanbai.app import run_app
    run_app(port=ui_port)


def main() -> None:
    """Entry point for the `kanbai` console script."""
    # Import commands module to register all CLI commands with the app
    import kanbai.commands  # noqa: F401
    app()


if __name__ == "__main__":
    main()
